public class Job {

    private String role;
    private String salary;
    private String id;

    public String getRole() {
        return role;
    }

    public String getSalary() {
        return salary;
    }

    public String getId() {
        return id;
    }

    public void setRole(String role) {
        this.role = role;
    }

    public void setSalary(String salary) {
        this.salary = salary;
    }

    public void setId(String id) {
        this.id = id;
    }
}
